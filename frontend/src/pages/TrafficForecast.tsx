import React, { useState, useEffect } from 'react';
import {
  ResponsiveContainer,
  LineChart,
  Line,
  BarChart,
  Bar,
  XAxis,
  YAxis,
  Tooltip,
  CartesianGrid,
  Legend,
  ReferenceArea,
} from 'recharts';
import { fetchRoadSegments, fetch24HourForecast, fetchModelInfo } from '../services/trafficApi';
import type { RoadSegment, HourlyForecast, ModelInfoResponse } from '../types';

export const TrafficForecast: React.FC = () => {
  const [roadSegments, setRoadSegments] = useState<RoadSegment[]>([]);
  const [selectedRoadId, setSelectedRoadId] = useState<string>('RS-01');
  const [forecastDate, setForecastDate] = useState<string>(
    () => new Date().toISOString().split('T')[0]
  );
  const [forecasts, setForecasts] = useState<HourlyForecast[]>([]);
  const [modelInfo, setModelInfo] = useState<ModelInfoResponse | null>(null);

  const [isLoading, setIsLoading] = useState<boolean>(true);
  const [errorMsg, setErrorMsg] = useState<string | null>(null);

  // Load Roads on Mount
  useEffect(() => {
    const loadRoads = async () => {
      try {
        const resp = await fetchRoadSegments();
        setRoadSegments(resp.roads);
        if (resp.roads.length > 0) {
          setSelectedRoadId(resp.roads[0].road_segment_id);
        }
      } catch (err) {
        console.error('Error fetching roads:', err);
      }
    };
    loadRoads();
  }, []);

  // Fetch 24-hour forecast and model info
  useEffect(() => {
    if (!selectedRoadId) return;

    const loadData = async () => {
      setIsLoading(true);
      setErrorMsg(null);
      try {
        const [fData, mData] = await Promise.all([
          fetch24HourForecast(selectedRoadId, forecastDate),
          fetchModelInfo(),
        ]);
        setForecasts(fData.forecasts);
        setModelInfo(mData);
      } catch (err: any) {
        console.error('Error fetching forecast:', err);
        setErrorMsg('Failed to load traffic forecast from backend.');
      } finally {
        setIsLoading(false);
      }
    };

    loadData();
  }, [selectedRoadId, forecastDate]);

  const selectedRoad = roadSegments.find((r) => r.road_segment_id === selectedRoadId);

  // Calculate morning, afternoon, evening averages from forecast
  const morningData = forecasts.filter((f) => 7 <= f.hour && f.hour <= 11);
  const afternoonData = forecasts.filter((f) => 12 <= f.hour && f.hour <= 16);
  const eveningData = forecasts.filter((f) => 17 <= f.hour && f.hour <= 21);

  const avgSpd = (arr: HourlyForecast[]) =>
    arr.length ? (arr.reduce((acc, c) => acc + c.predicted_speed_kmh, 0) / arr.length).toFixed(1) : '--';

  const avgVol = (arr: HourlyForecast[]) =>
    arr.length ? Math.round(arr.reduce((acc, c) => acc + c.predicted_volume, 0) / arr.length) : '--';

  return (
    <div className="flex flex-col gap-space-lg w-full pb-space-2xl">
      {/* Page Header */}
      <div className="flex flex-wrap items-center justify-between gap-space-md bg-surface-container-low p-space-md lg:p-space-lg rounded-xl border border-outline-variant/20 shadow-sm">
        <div className="flex flex-col">
          <div className="flex items-center gap-2">
            <span className="font-headline-lg text-headline-lg font-bold text-on-surface">
              24-Hour Traffic Forecast
            </span>
            <span className="px-2 py-0.5 rounded bg-primary-container/20 text-primary font-label-caps text-label-caps font-bold">
              MACHINE LEARNING INFERENCE
            </span>
          </div>
          <span className="font-body-sm text-body-sm text-on-surface-variant mt-1">
            Predictive travel times, corridor speeds, and anticipated congestion profiles generated by the trained XGBoost model
          </span>
        </div>

        {/* Model Provenance Banner */}
        <div className="px-3 py-1.5 rounded-lg bg-surface-container border border-outline-variant/30 text-xs font-mono text-on-surface-variant flex items-center gap-2">
          <span className="w-2 h-2 rounded-full bg-primary animate-pulse"></span>
          <span>Engine: XGBoost Regressor (Demo Data Trained)</span>
        </div>
      </div>

      {/* Control Toolbar */}
      <div className="bg-surface-container-low p-space-md rounded-xl border border-outline-variant/20 shadow-sm flex flex-wrap items-center justify-between gap-space-md">
        <div className="flex items-center gap-3">
          <span className="text-xs font-semibold text-on-surface-variant">Select Road Corridor:</span>
          <select
            value={selectedRoadId}
            onChange={(e) => setSelectedRoadId(e.target.value)}
            className="px-3 py-1.5 rounded-lg bg-surface-container-lowest border border-outline-variant/30 text-on-surface text-xs font-medium focus:outline-none focus:border-primary"
          >
            {roadSegments.map((r) => (
              <option key={r.road_segment_id} value={r.road_segment_id}>
                {r.road_segment_id}: {r.road_name} ({r.road_length_km} km)
              </option>
            ))}
          </select>
        </div>

        <div className="flex items-center gap-3">
          <span className="text-xs font-semibold text-on-surface-variant">Forecast Date:</span>
          <input
            type="date"
            value={forecastDate}
            onChange={(e) => setForecastDate(e.target.value)}
            className="px-3 py-1.5 rounded-lg bg-surface-container-lowest border border-outline-variant/30 text-on-surface text-xs font-medium"
          />
        </div>
      </div>

      {errorMsg && (
        <div className="p-space-md rounded-xl bg-error/10 border border-error/30 text-error flex items-center gap-3">
          <span className="material-symbols-outlined text-[20px]">error</span>
          <span className="text-sm">{errorMsg}</span>
        </div>
      )}

      {/* Diurnal Period Comparison Breakdown Cards */}
      <div className="grid grid-cols-1 sm:grid-cols-3 gap-space-md">
        {/* Morning Rush (07:00 - 11:00) */}
        <div className="p-space-md rounded-xl bg-surface-container-low border border-outline-variant/20 shadow-sm flex flex-col justify-between">
          <div className="flex items-center justify-between">
            <span className="font-label-caps text-[11px] font-bold uppercase text-amber-500">
              Morning Inflow (07:00 - 11:00)
            </span>
            <span className="material-symbols-outlined text-amber-500 text-[18px]">wb_sunny</span>
          </div>
          <div className="grid grid-cols-2 gap-2 mt-3">
            <div className="flex flex-col">
              <span className="text-[10px] text-on-surface-variant uppercase font-mono">Avg Speed</span>
              <span className="font-display-lg text-lg font-bold text-on-surface">{avgSpd(morningData)} km/h</span>
            </div>
            <div className="flex flex-col">
              <span className="text-[10px] text-on-surface-variant uppercase font-mono">Avg Flow</span>
              <span className="font-display-lg text-lg font-bold text-amber-500">{avgVol(morningData)} veh/h</span>
            </div>
          </div>
          <span className="text-[11px] text-on-surface-variant mt-2 font-mono">
            Commuter influx: Higher density on inbound lanes
          </span>
        </div>

        {/* Afternoon Inter-Peak (12:00 - 16:00) */}
        <div className="p-space-md rounded-xl bg-surface-container-low border border-outline-variant/20 shadow-sm flex flex-col justify-between">
          <div className="flex items-center justify-between">
            <span className="font-label-caps text-[11px] font-bold uppercase text-tertiary">
              Afternoon Inter-Peak (12:00 - 16:00)
            </span>
            <span className="material-symbols-outlined text-tertiary text-[18px]">wb_twilight</span>
          </div>
          <div className="grid grid-cols-2 gap-2 mt-3">
            <div className="flex flex-col">
              <span className="text-[10px] text-on-surface-variant uppercase font-mono">Avg Speed</span>
              <span className="font-display-lg text-lg font-bold text-on-surface">{avgSpd(afternoonData)} km/h</span>
            </div>
            <div className="flex flex-col">
              <span className="text-[10px] text-on-surface-variant uppercase font-mono">Avg Flow</span>
              <span className="font-display-lg text-lg font-bold text-tertiary">{avgVol(afternoonData)} veh/h</span>
            </div>
          </div>
          <span className="text-[11px] text-on-surface-variant mt-2 font-mono">
            Stable arterial flow: Near free-flow conditions
          </span>
        </div>

        {/* Evening Rush (17:00 - 21:00) */}
        <div className="p-space-md rounded-xl bg-surface-container-low border border-outline-variant/20 shadow-sm flex flex-col justify-between">
          <div className="flex items-center justify-between">
            <span className="font-label-caps text-[11px] font-bold uppercase text-error">
              Evening Rush (17:00 - 21:00)
            </span>
            <span className="material-symbols-outlined text-error text-[18px]">bedtime</span>
          </div>
          <div className="grid grid-cols-2 gap-2 mt-3">
            <div className="flex flex-col">
              <span className="text-[10px] text-on-surface-variant uppercase font-mono">Avg Speed</span>
              <span className="font-display-lg text-lg font-bold text-error">{avgSpd(eveningData)} km/h</span>
            </div>
            <div className="flex flex-col">
              <span className="text-[10px] text-on-surface-variant uppercase font-mono">Avg Flow</span>
              <span className="font-display-lg text-lg font-bold text-error">{avgVol(eveningData)} veh/h</span>
            </div>
          </div>
          <span className="text-[11px] text-on-surface-variant mt-2 font-mono">
            Heavy outflow: Queue propagation at signalized bottlenecks
          </span>
        </div>
      </div>

      {/* Chart 1: 24-Hour Predicted Travel Time Curve */}
      <div className="p-space-lg rounded-xl bg-surface-container-low border border-outline-variant/20 shadow-sm flex flex-col">
        <div className="flex items-center justify-between mb-4">
          <div className="flex flex-col">
            <span className="font-headline-sm font-semibold text-on-surface">
              Predicted Segment Travel Time Across 24 Hours
            </span>
            <span className="font-body-sm text-xs text-on-surface-variant">
              Unit: Seconds (s) for {selectedRoad?.road_name} ({selectedRoad?.road_length_km} km)
            </span>
          </div>
          <span className="material-symbols-outlined text-primary text-[20px]">timer</span>
        </div>

        <div className="w-full h-72">
          <ResponsiveContainer width="100%" height="100%">
            <LineChart data={forecasts} margin={{ top: 10, right: 20, left: 0, bottom: 20 }}>
              <CartesianGrid strokeDasharray="3 3" opacity={0.15} />
              <XAxis dataKey="hour" tickFormatter={(h) => `${h}:00`} tick={{ fontSize: 11, fill: 'currentColor' }} />
              <YAxis unit="s" tick={{ fontSize: 11, fill: 'currentColor' }} />
              <Tooltip
                formatter={(val: any) => [`${Number(val).toFixed(1)}s`, 'Predicted Travel Time']}
                labelFormatter={(h) => `Time: ${h}:00`}
                contentStyle={{ backgroundColor: '#1c2028', borderColor: '#3d494c', color: '#fff' }}
              />
              {/* Highlight Rush Hours */}
              <ReferenceArea x1={8} x2={10} fill="#f59e0b" fillOpacity={0.1} />
              <ReferenceArea x1={17} x2={20} fill="#ef4444" fillOpacity={0.1} />
              <Line
                type="monotone"
                dataKey="predicted_travel_time_seconds"
                stroke="#06b6d4"
                strokeWidth={3}
                dot={{ r: 3 }}
                activeDot={{ r: 6 }}
              />
            </LineChart>
          </ResponsiveContainer>
        </div>
      </div>

      {/* Chart 2: 24-Hour Predicted Speed vs Flow Rate */}
      <div className="grid grid-cols-1 lg:grid-cols-2 gap-space-lg">
        {/* Predicted Speed */}
        <div className="p-space-lg rounded-xl bg-surface-container-low border border-outline-variant/20 shadow-sm flex flex-col">
          <div className="flex items-center justify-between mb-4">
            <div className="flex flex-col">
              <span className="font-headline-sm font-semibold text-on-surface">Predicted Velocity Profile</span>
              <span className="font-body-sm text-xs text-on-surface-variant">Unit: km/h (Target limit: {selectedRoad?.speed_limit_kmh} km/h)</span>
            </div>
            <span className="material-symbols-outlined text-tertiary text-[20px]">speed</span>
          </div>

          <div className="w-full h-64">
            <ResponsiveContainer width="100%" height="100%">
              <LineChart data={forecasts} margin={{ top: 10, right: 20, left: 0, bottom: 20 }}>
                <CartesianGrid strokeDasharray="3 3" opacity={0.15} />
                <XAxis dataKey="hour" tickFormatter={(h) => `${h}:00`} tick={{ fontSize: 11, fill: 'currentColor' }} />
                <YAxis unit=" km/h" domain={[0, 'auto']} tick={{ fontSize: 11, fill: 'currentColor' }} />
                <Tooltip
                  formatter={(val: any) => [`${Number(val).toFixed(1)} km/h`, 'Predicted Speed']}
                  labelFormatter={(h) => `Time: ${h}:00`}
                  contentStyle={{ backgroundColor: '#1c2028', borderColor: '#3d494c', color: '#fff' }}
                />
                <Line
                  type="monotone"
                  dataKey="predicted_speed_kmh"
                  stroke="#10b981"
                  strokeWidth={2.5}
                  dot={{ r: 2 }}
                />
              </LineChart>
            </ResponsiveContainer>
          </div>
        </div>

        {/* Predicted Volume */}
        <div className="p-space-lg rounded-xl bg-surface-container-low border border-outline-variant/20 shadow-sm flex flex-col">
          <div className="flex items-center justify-between mb-4">
            <div className="flex flex-col">
              <span className="font-headline-sm font-semibold text-on-surface">Anticipated Hourly Demand</span>
              <span className="font-body-sm text-xs text-on-surface-variant">Unit: Vehicles per Hour (veh/h)</span>
            </div>
            <span className="material-symbols-outlined text-primary text-[20px]">traffic</span>
          </div>

          <div className="w-full h-64">
            <ResponsiveContainer width="100%" height="100%">
              <BarChart data={forecasts} margin={{ top: 10, right: 20, left: 0, bottom: 20 }}>
                <CartesianGrid strokeDasharray="3 3" opacity={0.15} />
                <XAxis dataKey="hour" tickFormatter={(h) => `${h}:00`} tick={{ fontSize: 11, fill: 'currentColor' }} />
                <YAxis unit=" veh" tick={{ fontSize: 11, fill: 'currentColor' }} />
                <Tooltip
                  formatter={(val: any) => [`${Math.round(val)} veh/h`, 'Predicted Volume']}
                  labelFormatter={(h) => `Time: ${h}:00`}
                  contentStyle={{ backgroundColor: '#1c2028', borderColor: '#3d494c', color: '#fff' }}
                />
                <Bar dataKey="predicted_volume" fill="#0284c7" radius={[4, 4, 0, 0]} />
              </BarChart>
            </ResponsiveContainer>
          </div>
        </div>
      </div>

      {/* Model Architecture & Evaluation Telemetry Card */}
      {modelInfo && (
        <div className="p-space-lg rounded-xl bg-surface-container-low border border-outline-variant/20 shadow-sm flex flex-col gap-space-md">
          <div className="flex items-center justify-between border-b border-outline-variant/20 pb-2">
            <div className="flex items-center gap-2">
              <span className="material-symbols-outlined text-primary text-[20px]">psychology</span>
              <span className="font-headline-sm font-semibold text-on-surface">
                Machine Learning Model Telemetry
              </span>
            </div>
            <span className="font-mono text-xs text-on-surface-variant">
              Target: travel_time_seconds
            </span>
          </div>

          <div className="grid grid-cols-1 sm:grid-cols-4 gap-space-md">
            <div className="p-space-sm rounded-lg bg-surface-container border border-outline-variant/10 flex flex-col">
              <span className="text-[10px] text-on-surface-variant font-mono uppercase">Model Architecture</span>
              <span className="font-headline-sm text-sm font-bold text-on-surface mt-1 truncate" title={modelInfo.model_type}>
                {modelInfo.model_type.split('(')[0]}
              </span>
              <span className="text-[10px] text-tertiary mt-0.5 font-mono">Gradient Boosted Trees</span>
            </div>

            <div className="p-space-sm rounded-lg bg-surface-container border border-outline-variant/10 flex flex-col">
              <span className="text-[10px] text-on-surface-variant font-mono uppercase">Test MAE (Error)</span>
              <span className="font-display-lg text-lg font-bold text-primary mt-1">
                {modelInfo.mae}s
              </span>
              <span className="text-[10px] text-on-surface-variant mt-0.5 font-mono">Mean Absolute Error</span>
            </div>

            <div className="p-space-sm rounded-lg bg-surface-container border border-outline-variant/10 flex flex-col">
              <span className="text-[10px] text-on-surface-variant font-mono uppercase">Test RMSE</span>
              <span className="font-display-lg text-lg font-bold text-on-surface mt-1">
                {modelInfo.rmse}s
              </span>
              <span className="text-[10px] text-on-surface-variant mt-0.5 font-mono">Root Mean Squared Error</span>
            </div>

            <div className="p-space-sm rounded-lg bg-surface-container border border-outline-variant/10 flex flex-col">
              <span className="text-[10px] text-on-surface-variant font-mono uppercase">Training Samples</span>
              <span className="font-display-lg text-lg font-bold text-tertiary mt-1">
                {modelInfo.training_records.toLocaleString()}
              </span>
              <span className="text-[10px] text-on-surface-variant mt-0.5 font-mono">Chronological Train Split</span>
            </div>
          </div>

          <div className="p-space-sm rounded-lg bg-surface-container-lowest border border-outline-variant/20 text-xs font-mono text-on-surface-variant flex flex-col gap-1">
            <div className="flex justify-between">
              <span>Features Extracted:</span>
              <span className="text-on-surface">{modelInfo.features_used.join(', ')}</span>
            </div>
            <div className="flex justify-between">
              <span>Data Split Strategy:</span>
              <span className="text-on-surface">Strict Chronological (70% Train, 15% Val, 15% Test — No Lookahead Leakage)</span>
            </div>
            <div className="text-amber-500 text-[11px] mt-1 pt-1 border-t border-outline-variant/10">
              ⚠️ Note: {modelInfo.note}
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
